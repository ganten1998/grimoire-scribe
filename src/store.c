static char g_root[512];
static float g_dpi = 300.f;
static int g_w = 1860, g_h = 2480;

void store_set_device(float dpi, int w, int h) {
    if (dpi > 50.f) g_dpi = dpi;
    // Pages are portrait whatever way the screen was turned at launch.
    if (w > 0 && h > 0) {
        g_w = w < h ? w : h;
        g_h = w < h ? h : w;
    }
}
float store_dpi(void) { return g_dpi; }
void store_page_size(int *w, int *h) {
    *w = g_w;
    *h = g_h;
}

// A page size a notebook can have: a screen's (bigger ones are damage; export.c refuses them too).
static bool page_size_ok(long w, long h) { return w >= 100 && h >= 100 && w <= 6000 && h <= 6000; }
// A size as written in an ini value ("1986"), 0 for one that is no size at all.
static int size_value(const char *v, char **end) {
    long x = strtol(v, end, 10);
    return x > 0 && x <= 100000 ? (int)x : 0;
}

void store_notebook_page_size(const NotebookInfo *nb, int *w, int *h) {
    bool own = page_size_ok(nb->page_w, nb->page_h);
    *w = own ? nb->page_w : g_w;
    *h = own ? nb->page_h : g_h;
}
const char *store_root(void) { return g_root; }

int store_init(const char *root) {
    strlcpy_q(g_root, root, sizeof g_root);
    char p[600];
    if (mkdir_p(root) != 0) {
        qlog("store: cannot create %s", root);
        return -1;
    }
    snprintf(p, sizeof p, "%s/notebooks", root);
    mkdir_p(p);
    snprintf(p, sizeof p, "%s/trash", root);
    mkdir_p(p);
    return 0;
}

// Ids are generated by us; reject anything that could escape the notebooks dir.
static bool id_ok(const char *id) {
    if (!id || !*id || strlen(id) >= STORE_ID_LEN) return false;
    for (const char *c = id; *c; c++)
        if (!((*c >= '0' && *c <= '9') || (*c >= 'a' && *c <= 'z') || (*c >= 'A' && *c <= 'Z') || *c == '-' ||
              *c == '_'))
            return false;
    return true;
}

int store_notebook_dir(const char *id, char *buf, size_t cap) {
    if (!id_ok(id)) return -1;
    snprintf(buf, cap, "%s/notebooks/%s", g_root, id);
    return 0;
}

// ---- text ----

// A growing text buffer: appends never run past it, and a failed allocation sticks (err).
typedef struct {
    char *d;
    size_t n, cap;
    bool err;
} Sb;

static bool sb_room(Sb *b, size_t more) {
    if (b->err) return false;
    if (b->n + more < b->cap) return true;
    size_t nc = b->cap ? b->cap : 1024;
    while (nc <= b->n + more) nc *= 2;
    char *nd = realloc(b->d, nc);
    if (!nd) {
        b->err = true;
        return false;
    }
    b->d = nd;
    b->cap = nc;
    return true;
}

static void sb_put(Sb *b, const char *s, size_t len) {
    if (!sb_room(b, len)) return;
    memcpy(b->d + b->n, s, len);
    b->n += len;
    b->d[b->n] = 0;
}

static void sb_printf(Sb *b, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
static void sb_printf(Sb *b, const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    int k = vsnprintf(NULL, 0, fmt, ap);
    va_end(ap);
    if (k < 0) {
        b->err = true;
        return;
    }
    if (!sb_room(b, (size_t)k)) return;
    va_start(ap, fmt);
    vsnprintf(b->d + b->n, b->cap - b->n, fmt, ap);
    va_end(ap);
    b->n += (size_t)k;
}

// A note about something that stays as it is (a copy kept aside, lines that do not fit) is logged
// the first time it comes up in a run, not on every listing or opening of the notebook.
static void qlog_once(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
static void qlog_once(const char *fmt, ...) {
    static uint64_t seen[256];
    static int nseen;
    char msg[512];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(msg, sizeof msg, fmt, ap);
    va_end(ap);
    uint64_t h = 14695981039346656037ull;  // FNV-1a of the whole line
    for (const char *c = msg; *c; c++) h = (h ^ (uint8_t)*c) * 1099511628211ull;
    for (int i = 0; i < nseen; i++)
        if (seen[i] == h) return;
    if (nseen < (int)(sizeof seen / sizeof seen[0])) seen[nseen++] = h;
    qlog("%s", msg);
}

// ---- tiny ini ----

// Returns false for a key it does not know: the line then goes to `unknown` (if given), so keys
// a newer version wrote can be written back (docs/FORMAT.md).
typedef bool (*IniCb)(void *ctx, const char *key, const char *val);
typedef void (*IniUnknown)(void *ctx, const char *key, const char *val);

static int ini_parse_file(const char *path, IniCb cb, IniUnknown unknown, void *ctx) {
    size_t len;
    char *txt = read_file(path, &len);
    if (!txt) return -1;
    char *save = NULL;
    for (char *line = strtok_r(txt, "\n", &save); line; line = strtok_r(NULL, "\n", &save)) {
        char *eq = strchr(line, '=');
        if (!eq || line[0] == '#') continue;
        *eq = 0;
        char *v = eq + 1;
        size_t vl = strlen(v);
        if (vl && v[vl - 1] == '\r') v[vl - 1] = 0;
        if (!cb(ctx, line, v) && unknown) unknown(ctx, line, v);
    }
    free(txt);
    return 0;
}

// Names are single-line in the ini. One longer than the field is cut short at a character's
// start, never inside a UTF-8 character: a name cut in the middle of one would be written back
// so, and its mirror PDF's path and the share pages would carry a broken character.
static void clean_line(char *dst, const char *src, size_t cap) {
    size_t n = strlcpy_q(dst, src, cap);
    if (src && ((uint8_t)src[n] & 0xC0) == 0x80) {  // cut inside a character: drop its first bytes
        while (n > 0 && ((uint8_t)dst[n - 1] & 0xC0) == 0x80) n--;
        if (n > 0 && ((uint8_t)dst[n - 1] & 0xC0) == 0xC0) n--;
        dst[n] = 0;
    }
    for (size_t i = 0; i < n; i++)
        if (dst[i] == '\n' || dst[i] == '\r') dst[i] = ' ';
}

// ---- notebooks ----

static bool info_cb(void *ctx, const char *k, const char *v) {
    NotebookInfo *nb = ctx;
    if (!strcmp(k, "name")) clean_line(nb->name, v, sizeof nb->name);
    else if (!strcmp(k, "folder")) clean_line(nb->folder, v, sizeof nb->folder);
    // A paper this build does not know stays as it is: new pages get it, a newer version draws it.
    else if (!strcmp(k, "paper")) nb->paper = (PaperKind)(uint32_t)strtoul(v, NULL, 10);
    else if (!strcmp(k, "created")) nb->created = atoll(v);
    else if (!strcmp(k, "modified")) nb->modified = atoll(v);
    else if (!strcmp(k, "last_page")) nb->last_page = atoi(v);
    else if (!strcmp(k, "next_page_id")) nb->next_page_id = (uint32_t)strtoul(v, NULL, 10);
    // The page size (1.1 on). A value no screen has is not kept: store_load_info finds the size.
    else if (!strcmp(k, "page_w")) nb->page_w = size_value(v, NULL);
    else if (!strcmp(k, "page_h")) nb->page_h = size_value(v, NULL);
    else if (!strcmp(k, "pages")) {
        nb->npages = 0;
        const char *p = v;
        while (*p && nb->npages < STORE_MAX_PAGES) {
            char *end;
            unsigned long id = strtoul(p, &end, 10);
            if (end == p) break;
            if (id > 0) nb->page_ids[nb->npages++] = (uint32_t)id;
            p = *end == ',' ? end + 1 : end;
        }
    } else return false;
    return true;
}

// notebook.ini lines this build does not know, written back after the keys it knows. Whole lines
// only: one that no longer fits is left out (counted here, logged by store_load_info).
static int g_info_dropped;

static void info_unknown(void *ctx, const char *k, const char *v) {
    NotebookInfo *nb = ctx;
    size_t have = strnlen(nb->extra, sizeof nb->extra), need = strlen(k) + strlen(v) + 2;
    if (have + need >= sizeof nb->extra) {
        g_info_dropped++;
        return;
    }
    snprintf(nb->extra + have, sizeof nb->extra - have, "%s=%s\n", k, v);
}

static int cmp_u32(const void *a, const void *b) {
    uint32_t x = *(const uint32_t *)a, y = *(const uint32_t *)b;
    return x < y ? -1 : x > y;
}

static void rebuild_pages(const char *dir, NotebookInfo *nb) {
    DIR *d = opendir(dir);
    if (!d) return;
    struct dirent *e;
    while ((e = readdir(d)) && nb->npages < STORE_MAX_PAGES) {
        unsigned long id;
        char tail[8];
        if (sscanf(e->d_name, "p%lu.qp%7s", &id, tail) == 2 && !strcmp(tail, "g") && id > 0 && id < 0x7fffffff)
            nb->page_ids[nb->npages++] = (uint32_t)id;
    }
    closedir(d);
    qsort(nb->page_ids, (size_t)nb->npages, sizeof nb->page_ids[0], cmp_u32);
}

static int g_corrupt_pages;
int store_take_corrupt_count(void) {
    int n = g_corrupt_pages;
    g_corrupt_pages = 0;
    return n;
}

static bool page_file_size(const char *path, int *w, int *h);

// The size most of a notebook's page files have (each from its first 16 bytes); a tie goes to the
// size that comes first in page order. Pages without one (missing, damaged) do not count. Leaves
// nb->page_w x page_h as it is when no page has a size. Stops reading once one size has more than
// half the pages, so a notebook of one size reads half its page files.
static void notebook_size_from_pages(const char *dir, NotebookInfo *nb) {
    enum { SIZES = 4 };  // sizes counted, in the order first seen (a fifth is a page of damage)
    int sw[SIZES], sh[SIZES], count[SIZES], nsizes = 0;
    char path[700];
    for (int i = 0; i < nb->npages; i++) {
        int w, h, k = 0;
        snprintf(path, sizeof path, "%s/p%u.qpg", dir, nb->page_ids[i]);
        if (!page_file_size(path, &w, &h)) continue;
        while (k < nsizes && (sw[k] != w || sh[k] != h)) k++;
        if (k == nsizes) {
            if (nsizes == SIZES) continue;
            sw[k] = w;
            sh[k] = h;
            count[k] = 0;
            nsizes++;
        }
        if (++count[k] * 2 > nb->npages) break;  // more than half: no other size can have more
    }
    int best = -1;
    for (int k = 0; k < nsizes; k++)
        if (best < 0 || count[k] > count[best]) best = k;  // a tie: the one seen first
    if (best < 0) return;
    nb->page_w = sw[best];
    nb->page_h = sh[best];
}

// Set by store_load_info when it had to work the page size out from the page files.
static bool g_size_derived;

int store_load_info(const char *id_in, NotebookInfo *out) {
    char dir[600], path[700], id[STORE_ID_LEN];
    strlcpy_q(id, id_in, sizeof id);  // id_in may be out->id itself: copy it before the memset
    if (store_notebook_dir(id, dir, sizeof dir) != 0) return -1;
    memset(out, 0, sizeof *out);
    strlcpy_q(out->id, id, sizeof out->id);
    snprintf(path, sizeof path, "%s/notebook.ini", dir);
    g_info_dropped = 0;
    if (ini_parse_file(path, info_cb, info_unknown, out) != 0) return -1;
    if (g_info_dropped)
        qlog_once("store: %s: %d unknown notebook.ini line(s) do not fit in the %d bytes kept, left out", id,
                  g_info_dropped, STORE_EXTRA_LEN);
    if (out->npages == 0) {
        // A damaged or empty notebook.ini: rebuild the page list from the page files, so the
        // next save cannot drop every page but the first.
        rebuild_pages(dir, out);
        if (out->npages > 0) qlog("store: %s had no page list, found %d page file(s)", id, out->npages);
    }
    if (out->npages == 0) {  // never leave a notebook without a page
        out->page_ids[0] = 1;
        out->npages = 1;
    }
    if (!page_size_ok(out->page_w, out->page_h)) {
        // No page size recorded (a notebook from before 1.1, or one 1.0.0-beta saved: it drops the
        // keys): the size most of its page files have, else the device's. The next save records
        // it. Most, not the first's: a version before 1.1 on a Scribe of the other size writes
        // each page it edits at that size, and 1.0.0-beta re-saves page 1 after a page delete.
        out->page_w = g_w;
        out->page_h = g_h;
        notebook_size_from_pages(dir, out);
        g_size_derived = true;
    }
    uint32_t maxid = 0;
    for (int i = 0; i < out->npages; i++)
        if (out->page_ids[i] > maxid) maxid = out->page_ids[i];
    if (out->next_page_id <= maxid) out->next_page_id = maxid + 1;
    out->last_page = clampi(out->last_page, 0, out->npages - 1);
    if (!out->name[0]) strlcpy_q(out->name, "Untitled", sizeof out->name);
    return 0;
}

static int write_info_at(const char *dir, const NotebookInfo *nb);

static int write_info(const NotebookInfo *nb) {
    char dir[600];
    if (store_notebook_dir(nb->id, dir, sizeof dir) != 0) return -1;
    return write_info_at(dir, nb);
}

int store_write_info_in(const char *dir, const NotebookInfo *nb) { return write_info_at(dir, nb); }

static int write_info_at(const char *dir, const NotebookInfo *nb) {
    char path[700];
    snprintf(path, sizeof path, "%s/notebook.ini", dir);
    char name[STORE_NAME_LEN], folder[STORE_NAME_LEN];
    clean_line(name, nb->name, sizeof name);
    clean_line(folder, nb->folder, sizeof folder);
    Sb b = {0};
    sb_printf(&b,
              "# Grimoire notebook\nname=%s\nfolder=%s\npaper=%u\ncreated=%lld\nmodified=%lld\n"
              "last_page=%d\nnext_page_id=%u\npages=",
              name, folder, (unsigned)nb->paper, (long long)nb->created, (long long)nb->modified, nb->last_page,
              nb->next_page_id);
    for (int i = 0; i < nb->npages && i < STORE_MAX_PAGES; i++) sb_printf(&b, "%s%u", i ? "," : "", nb->page_ids[i]);
    sb_put(&b, "\n", 1);
    int pw, ph;
    store_notebook_page_size(nb, &pw, &ph);
    sb_printf(&b, "page_w=%d\npage_h=%d\n", pw, ph);
    sb_put(&b, nb->extra, strnlen(nb->extra, sizeof nb->extra));  // keys a newer version wrote, as they were
    int rc = b.err ? -1 : write_file_atomic(path, b.d, b.n);
    free(b.d);
    return rc;
}

int store_save_info(NotebookInfo *nb) {
    nb->modified = wall_time();
    return write_info(nb);
}

static void page_path(const NotebookInfo *nb, uint32_t pid, char *buf, size_t cap) {
    snprintf(buf, cap, "%s/notebooks/%s/p%u.qpg", g_root, nb->id, pid);
}

static int write_page_at(const char *path, const Page *p) {
    uint8_t *data;
    size_t len;
    if (page_serialize(p, &data, &len) != 0) return -1;
    int rc = write_file_atomic(path, data, len);
    free(data);
    return rc;
}

static int write_page_file(const NotebookInfo *nb, uint32_t pid, const Page *p) {
    char path[700];
    page_path(nb, pid, path, sizeof path);
    return write_page_at(path, p);
}

int store_write_page_in(const char *dir, uint32_t pid, const Page *p) {
    char path[700];
    snprintf(path, sizeof path, "%s/p%u.qpg", dir, pid);
    return write_page_at(path, p);
}

// ---- bg/pages.ini: the image paper of every page that has one ----
//
// A page's paper is in its own file, but 1.0.0-beta saves a page whose paper it does not know as
// version 1 Blank, and the page's picture would be lost to it. This list, which no older version
// touches, brings it back (docs/FORMAT.md, Image papers): every save that makes a page's paper an
// image paper, or makes it stop being one, updates it.

typedef struct {
    uint32_t pid, kind;
} SideEntry;
typedef struct {
    SideEntry *e;
    int n, cap;
} Side;

static void side_path(const char *bgdir, char *buf, size_t cap) { snprintf(buf, cap, "%s/pages.ini", bgdir); }

static bool side_get(const Side *s, uint32_t pid, uint32_t *kind) {
    for (int i = 0; i < s->n; i++)
        if (s->e[i].pid == pid) {
            *kind = s->e[i].kind;
            return true;
        }
    return false;
}

// Lists pid with kind, or (kind 0) takes it off the list. -1 out of memory.
static int side_set(Side *s, uint32_t pid, uint32_t kind) {
    for (int i = 0; i < s->n; i++) {
        if (s->e[i].pid != pid) continue;
        if (kind) s->e[i].kind = kind;
        else s->e[i] = s->e[--s->n];
        return 0;
    }
    if (!kind) return 0;
    if (s->n == s->cap) {
        int nc = s->cap ? s->cap * 2 : 16;
        SideEntry *ne = realloc(s->e, (size_t)nc * sizeof *ne);
        if (!ne) return -1;
        s->e = ne;
        s->cap = nc;
    }
    s->e[s->n++] = (SideEntry){pid, kind};
    return 0;
}

// Reads <bgdir>/pages.ini: lines p<page id>=<paper value>, for image papers only.
static void side_load(const char *bgdir, Side *s) {
    memset(s, 0, sizeof *s);
    char path[760];
    side_path(bgdir, path, sizeof path);
    size_t len;
    char *txt = read_file(path, &len);
    if (!txt) return;
    char *save = NULL;
    for (char *line = strtok_r(txt, "\n", &save); line; line = strtok_r(NULL, "\n", &save)) {
        unsigned long pid, kind;
        char *end;
        if (line[0] != 'p') continue;
        pid = strtoul(line + 1, &end, 10);
        if (end == line + 1 || *end != '=' || pid == 0 || pid >= 0x7fffffff) continue;
        kind = strtoul(end + 1, NULL, 10);
        if (paper_is_image((PaperKind)(uint32_t)kind) && side_set(s, (uint32_t)pid, (uint32_t)kind) != 0) break;
    }
    free(txt);
}

static int cmp_side(const void *a, const void *b) {
    const SideEntry *x = a, *y = b;
    return x->pid < y->pid ? -1 : x->pid > y->pid;
}

static int side_save(const char *bgdir, Side *s) {
    qsort(s->e, (size_t)s->n, sizeof *s->e, cmp_side);
    Sb b = {0};
    sb_printf(&b, "# Grimoire: the image paper of each page that has one (docs/FORMAT.md)\n");
    for (int i = 0; i < s->n; i++) sb_printf(&b, "p%u=%u\n", s->e[i].pid, s->e[i].kind);
    char path[760];
    side_path(bgdir, path, sizeof path);
    int rc = b.err || mkdir_p(bgdir) != 0 ? -1 : write_file_atomic(path, b.d, b.n);
    free(b.d);
    return rc;
}

static int notebook_bg_dir(const NotebookInfo *nb, char *buf, size_t cap) {
    char dir[600];
    if (store_notebook_dir(nb->id, dir, sizeof dir) != 0) return -1;
    snprintf(buf, cap, "%s/bg", dir);
    return 0;
}

// Brings bg/pages.ini in step with page pid's paper: an image paper listed, any other not.
static void side_note(const NotebookInfo *nb, uint32_t pid, PaperKind paper) {
    char bgdir[700], path[760];
    if (notebook_bg_dir(nb, bgdir, sizeof bgdir) != 0) return;
    side_path(bgdir, path, sizeof path);
    bool image = paper_is_image(paper);
    if (!image && access(path, F_OK) != 0) return;  // nothing listed: nothing to take off
    Side s;
    side_load(bgdir, &s);
    uint32_t have;
    bool listed = side_get(&s, pid, &have);
    if (image ? !(listed && have == (uint32_t)paper) : listed) {
        if (side_set(&s, pid, image ? (uint32_t)paper : 0) != 0 || side_save(bgdir, &s) != 0)
            qlog("store: %s: could not update bg/pages.ini for p%u.qpg", nb->id, pid);
    }
    free(s.e);
}

// A page an older version saved as blank paper (version 1 Blank) that bg/pages.ini lists with an
// image paper gets its picture back: in this version a page only ever goes to Blank by a save that
// takes it off the list.
static void side_restore(const NotebookInfo *nb, uint32_t pid, Page *p) {
    if (p->paper != PAPER_BLANK || p->readonly) return;
    char bgdir[700], path[760];
    if (notebook_bg_dir(nb, bgdir, sizeof bgdir) != 0) return;
    side_path(bgdir, path, sizeof path);
    if (access(path, F_OK) != 0) return;
    Side s;
    side_load(bgdir, &s);
    uint32_t kind;
    if (side_get(&s, pid, &kind)) {
        p->paper = (PaperKind)kind;
        qlog_once("store: %s: p%u.qpg was saved with blank paper by an older version; its picture comes back from "
                  "bg/pages.ini", nb->id, pid);
    }
    free(s.e);
}

int store_write_pages_list_in(const char *bgdir, const uint32_t *pids, const PaperKind *papers, int n) {
    Side s = {0};
    int rc = 0;
    for (int i = 0; i < n && rc == 0; i++)
        if (paper_is_image(papers[i])) rc = side_set(&s, pids[i], (uint32_t)papers[i]);
    if (rc == 0) rc = side_save(bgdir, &s);
    free(s.e);
    return rc;
}

PaperKind store_new_page_paper(const NotebookInfo *nb, PaperKind after) {
    if (!paper_is_document(after)) return after;
    return paper_is_document(nb->paper) ? PAPER_BLANK : nb->paper;
}

static void random_hex(char *out, int n) {
    uint8_t b[8] = {0};
    int fd = open("/dev/urandom", O_RDONLY);
    bool ok = fd >= 0 && read(fd, b, sizeof b) == (ssize_t)sizeof b;
    if (fd >= 0) close(fd);
    if (!ok) {
        uint32_t x = now_ms() ^ (uint32_t)getpid() * 2654435761u;
        memcpy(b, &x, sizeof x);
    }
    static const char hx[] = "0123456789abcdef";
    for (int i = 0; i < n; i++) out[i] = hx[(b[i / 2] >> ((i & 1) ? 0 : 4)) & 15];
    out[n] = 0;
}

void store_make_id(char id[STORE_ID_LEN]) {
    time_t t = (time_t)wall_time();
    struct tm tm;
    localtime_r(&t, &tm);
    char rnd[8];
    random_hex(rnd, 4);
    snprintf(id, STORE_ID_LEN, "%04d%02d%02d-%02d%02d%02d-%s", tm.tm_year + 1900, tm.tm_mon + 1, tm.tm_mday,
             tm.tm_hour, tm.tm_min, tm.tm_sec, rnd);
}

int store_create(const char *name, const char *folder, PaperKind paper, NotebookInfo *out) {
    NotebookInfo *nb = out;
    memset(nb, 0, sizeof *nb);
    time_t t = (time_t)wall_time();
    store_make_id(nb->id);
    clean_line(nb->name, name && *name ? name : "Untitled", sizeof nb->name);
    clean_line(nb->folder, folder ? folder : "", sizeof nb->folder);
    nb->paper = paper_sanitize((uint32_t)paper, PAPER_MEDIUM);
    nb->created = nb->modified = (int64_t)t;
    nb->npages = 1;
    nb->page_ids[0] = 1;
    nb->next_page_id = 2;
    nb->page_w = g_w;  // the device's page size, the notebook's wherever it is opened later
    nb->page_h = g_h;
    char dir[600], parent[600];
    snprintf(parent, sizeof parent, "%s/notebooks", g_root);
    if (mkdir_p(parent) != 0) return -1;
    // Two notebooks made in the same second must never share a directory: plain mkdir, and a
    // fresh random suffix if the name is taken.
    for (int attempt = 0;; attempt++) {
        store_notebook_dir(nb->id, dir, sizeof dir);
        if (mkdir(dir, 0755) == 0) break;
        if (errno != EEXIST || attempt >= 8) {
            qlog("store: cannot create %s: %s", dir, strerror(errno));
            return -1;
        }
        char rnd2[8];
        random_hex(rnd2, 4);
        memcpy(nb->id + strlen(nb->id) - 4, rnd2, 4);
    }
    Page *p = page_new(nb->page_w, nb->page_h, nb->paper);
    if (!p) return -1;
    strlcpy_q(p->nb, nb->id, sizeof p->nb);
    int rc = write_page_file(nb, 1, p);
    page_free(p);
    if (rc != 0) return -1;
    return write_info(nb);
}

int store_rename(const char *id, const char *name) {
    NotebookInfo *nb = malloc(sizeof *nb);
    if (!nb) return -1;
    int rc = store_load_info(id, nb);
    if (rc == 0) {
        clean_line(nb->name, name, sizeof nb->name);
        rc = store_save_info(nb);
    }
    free(nb);
    return rc;
}

int store_set_folder(const char *id, const char *folder) {
    NotebookInfo *nb = malloc(sizeof *nb);
    if (!nb) return -1;
    int rc = store_load_info(id, nb);
    if (rc == 0) {
        clean_line(nb->folder, folder ? folder : "", sizeof nb->folder);
        rc = store_save_info(nb);
    }
    free(nb);
    return rc;
}

static int move_to_trash(const char *src, const char *base) {
    char dst[800];
    snprintf(dst, sizeof dst, "%s/trash/%s-%lld", g_root, base, (long long)wall_time());
    if (rename(src, dst) != 0) {
        qlog("trash %s: %s", src, strerror(errno));
        return -1;
    }
    return 0;
}

int store_delete(const char *id) {
    char dir[600];
    if (store_notebook_dir(id, dir, sizeof dir) != 0) return -1;
    return move_to_trash(dir, id);
}

static int cmp_modified(const void *a, const void *b) {
    const NotebookInfo *x = a, *y = b;
    if (x->modified != y->modified) return x->modified < y->modified ? 1 : -1;
    return strcmp(x->id, y->id);
}

int store_list(NotebookInfo **out, int *n) {
    *out = NULL;
    *n = 0;
    char dir[600];
    snprintf(dir, sizeof dir, "%s/notebooks", g_root);
    DIR *d = opendir(dir);
    if (!d) return -1;
    int cap = 0;
    NotebookInfo *arr = NULL;
    struct dirent *e;
    while ((e = readdir(d))) {
        if (e->d_name[0] == '.' || !id_ok(e->d_name)) continue;
        if (*n == cap) {
            int nc = cap ? cap * 2 : 16;
            NotebookInfo *na = realloc(arr, (size_t)nc * sizeof *na);
            if (!na) break;
            arr = na;
            cap = nc;
        }
        g_size_derived = false;
        if (store_load_info(e->d_name, &arr[*n]) == 0) {
            // A notebook from before 1.1: its size was worked out from its page files. Record it
            // now (as written, its modified time unchanged) so later listings read one file, not
            // half its pages.
            if (g_size_derived && write_info(&arr[*n]) != 0) qlog_once("store: could not record the page size of %s", e->d_name);
            (*n)++;
        } else qlog("store: skipping unreadable notebook %s", e->d_name);
    }
    closedir(d);
    if (*n) qsort(arr, (size_t)*n, sizeof *arr, cmp_modified);
    *out = arr;
    return 0;
}

