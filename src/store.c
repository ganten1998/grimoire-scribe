static char g_root[512];
static float g_dpi = 300.f;
static int g_w = 1860, g_h = 2480;

void store_set_device(float dpi, int w, int h) {
    if (dpi > 50.f) g_dpi = dpi;
    // Pages are portrait whatever way the screen was turned at launch.
    if (w > 0 && h > 0) {
        g_w = w < h ? w : h;
        g_h = w < h ? h : w;
    }
}
float store_dpi(void) { return g_dpi; }
void store_page_size(int *w, int *h) {
    *w = g_w;
    *h = g_h;
}
const char *store_root(void) { return g_root; }

int store_init(const char *root) {
    strlcpy_q(g_root, root, sizeof g_root);
    char p[600];
    if (mkdir_p(root) != 0) {
        qlog("store: cannot create %s", root);
        return -1;
    }
    snprintf(p, sizeof p, "%s/notebooks", root);
    mkdir_p(p);
    snprintf(p, sizeof p, "%s/trash", root);
    mkdir_p(p);
    return 0;
}

// Ids are generated by us; reject anything that could escape the notebooks dir.
static bool id_ok(const char *id) {
    if (!id || !*id || strlen(id) >= STORE_ID_LEN) return false;
    for (const char *c = id; *c; c++)
        if (!((*c >= '0' && *c <= '9') || (*c >= 'a' && *c <= 'z') || (*c >= 'A' && *c <= 'Z') || *c == '-' ||
              *c == '_'))
            return false;
    return true;
}

int store_notebook_dir(const char *id, char *buf, size_t cap) {
    if (!id_ok(id)) return -1;
    snprintf(buf, cap, "%s/notebooks/%s", g_root, id);
    return 0;
}

// ---- text ----

// A growing text buffer: appends never run past it, and a failed allocation sticks (err).
typedef struct {
    char *d;
    size_t n, cap;
    bool err;
} Sb;

static bool sb_room(Sb *b, size_t more) {
    if (b->err) return false;
    if (b->n + more < b->cap) return true;
    size_t nc = b->cap ? b->cap : 1024;
    while (nc <= b->n + more) nc *= 2;
    char *nd = realloc(b->d, nc);
    if (!nd) {
        b->err = true;
        return false;
    }
    b->d = nd;
    b->cap = nc;
    return true;
}

static void sb_put(Sb *b, const char *s, size_t len) {
    if (!sb_room(b, len)) return;
    memcpy(b->d + b->n, s, len);
    b->n += len;
    b->d[b->n] = 0;
}

static void sb_printf(Sb *b, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
static void sb_printf(Sb *b, const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    int k = vsnprintf(NULL, 0, fmt, ap);
    va_end(ap);
    if (k < 0) {
        b->err = true;
        return;
    }
    if (!sb_room(b, (size_t)k)) return;
    va_start(ap, fmt);
    vsnprintf(b->d + b->n, b->cap - b->n, fmt, ap);
    va_end(ap);
    b->n += (size_t)k;
}

// ---- tiny ini ----

// Returns false for a key it does not know: the line then goes to `unknown` (if given), so keys
// a newer version wrote can be written back (docs/FORMAT.md).
typedef bool (*IniCb)(void *ctx, const char *key, const char *val);
typedef void (*IniUnknown)(void *ctx, const char *key, const char *val);

static int ini_parse_file(const char *path, IniCb cb, IniUnknown unknown, void *ctx) {
    size_t len;
    char *txt = read_file(path, &len);
    if (!txt) return -1;
    char *save = NULL;
    for (char *line = strtok_r(txt, "\n", &save); line; line = strtok_r(NULL, "\n", &save)) {
        char *eq = strchr(line, '=');
        if (!eq || line[0] == '#') continue;
        *eq = 0;
        char *v = eq + 1;
        size_t vl = strlen(v);
        if (vl && v[vl - 1] == '\r') v[vl - 1] = 0;
        if (!cb(ctx, line, v) && unknown) unknown(ctx, line, v);
    }
    free(txt);
    return 0;
}

// Names are single-line in the ini.
static void clean_line(char *dst, const char *src, size_t cap) {
    size_t n = strlcpy_q(dst, src, cap);
    for (size_t i = 0; i < n; i++)
        if (dst[i] == '\n' || dst[i] == '\r') dst[i] = ' ';
}

// ---- notebooks ----

static bool info_cb(void *ctx, const char *k, const char *v) {
    NotebookInfo *nb = ctx;
    if (!strcmp(k, "name")) clean_line(nb->name, v, sizeof nb->name);
    else if (!strcmp(k, "folder")) clean_line(nb->folder, v, sizeof nb->folder);
    // A paper this build does not know stays as it is: new pages get it, a newer version draws it.
    else if (!strcmp(k, "paper")) nb->paper = (PaperKind)(uint32_t)strtoul(v, NULL, 10);
    else if (!strcmp(k, "created")) nb->created = atoll(v);
    else if (!strcmp(k, "modified")) nb->modified = atoll(v);
    else if (!strcmp(k, "last_page")) nb->last_page = atoi(v);
    else if (!strcmp(k, "next_page_id")) nb->next_page_id = (uint32_t)strtoul(v, NULL, 10);
    else if (!strcmp(k, "pages")) {
        nb->npages = 0;
        const char *p = v;
        while (*p && nb->npages < STORE_MAX_PAGES) {
            char *end;
            unsigned long id = strtoul(p, &end, 10);
            if (end == p) break;
            if (id > 0) nb->page_ids[nb->npages++] = (uint32_t)id;
            p = *end == ',' ? end + 1 : end;
        }
    } else return false;
    return true;
}

// notebook.ini lines this build does not know, written back after the keys it knows. Whole lines
// only: one that no longer fits is left out (and logged).
static void info_unknown(void *ctx, const char *k, const char *v) {
    NotebookInfo *nb = ctx;
    size_t have = strnlen(nb->extra, sizeof nb->extra), need = strlen(k) + strlen(v) + 2;
    if (have + need >= sizeof nb->extra) {
        qlog("store: %s: notebook.ini line \"%.40s\" does not fit, not kept", nb->id, k);
        return;
    }
    snprintf(nb->extra + have, sizeof nb->extra - have, "%s=%s\n", k, v);
}

static int cmp_u32(const void *a, const void *b) {
    uint32_t x = *(const uint32_t *)a, y = *(const uint32_t *)b;
    return x < y ? -1 : x > y;
}

static void rebuild_pages(const char *dir, NotebookInfo *nb) {
    DIR *d = opendir(dir);
    if (!d) return;
    struct dirent *e;
    while ((e = readdir(d)) && nb->npages < STORE_MAX_PAGES) {
        unsigned long id;
        char tail[8];
        if (sscanf(e->d_name, "p%lu.qp%7s", &id, tail) == 2 && !strcmp(tail, "g") && id > 0 && id < 0x7fffffff)
            nb->page_ids[nb->npages++] = (uint32_t)id;
    }
    closedir(d);
    qsort(nb->page_ids, (size_t)nb->npages, sizeof nb->page_ids[0], cmp_u32);
}

static int g_corrupt_pages;
int store_take_corrupt_count(void) {
    int n = g_corrupt_pages;
    g_corrupt_pages = 0;
    return n;
}

int store_load_info(const char *id_in, NotebookInfo *out) {
    char dir[600], path[700], id[STORE_ID_LEN];
    strlcpy_q(id, id_in, sizeof id);  // id_in may be out->id itself: copy it before the memset
    if (store_notebook_dir(id, dir, sizeof dir) != 0) return -1;
    memset(out, 0, sizeof *out);
    strlcpy_q(out->id, id, sizeof out->id);
    snprintf(path, sizeof path, "%s/notebook.ini", dir);
    if (ini_parse_file(path, info_cb, info_unknown, out) != 0) return -1;
    if (out->npages == 0) {
        // A damaged or empty notebook.ini: rebuild the page list from the page files, so the
        // next save cannot drop every page but the first.
        rebuild_pages(dir, out);
        if (out->npages > 0) qlog("store: %s had no page list, found %d page file(s)", id, out->npages);
    }
    if (out->npages == 0) {  // never leave a notebook without a page
        out->page_ids[0] = 1;
        out->npages = 1;
    }
    uint32_t maxid = 0;
    for (int i = 0; i < out->npages; i++)
        if (out->page_ids[i] > maxid) maxid = out->page_ids[i];
    if (out->next_page_id <= maxid) out->next_page_id = maxid + 1;
    out->last_page = clampi(out->last_page, 0, out->npages - 1);
    if (!out->name[0]) strlcpy_q(out->name, "Untitled", sizeof out->name);
    return 0;
}

static int write_info(const NotebookInfo *nb) {
    char dir[600], path[700];
    if (store_notebook_dir(nb->id, dir, sizeof dir) != 0) return -1;
    snprintf(path, sizeof path, "%s/notebook.ini", dir);
    char name[STORE_NAME_LEN], folder[STORE_NAME_LEN];
    clean_line(name, nb->name, sizeof name);
    clean_line(folder, nb->folder, sizeof folder);
    Sb b = {0};
    sb_printf(&b,
              "# Grimoire notebook\nname=%s\nfolder=%s\npaper=%u\ncreated=%lld\nmodified=%lld\n"
              "last_page=%d\nnext_page_id=%u\npages=",
              name, folder, (unsigned)nb->paper, (long long)nb->created, (long long)nb->modified, nb->last_page,
              nb->next_page_id);
    for (int i = 0; i < nb->npages && i < STORE_MAX_PAGES; i++) sb_printf(&b, "%s%u", i ? "," : "", nb->page_ids[i]);
    sb_put(&b, "\n", 1);
    sb_put(&b, nb->extra, strnlen(nb->extra, sizeof nb->extra));  // keys a newer version wrote, as they were
    int rc = b.err ? -1 : write_file_atomic(path, b.d, b.n);
    free(b.d);
    return rc;
}

int store_save_info(NotebookInfo *nb) {
    nb->modified = wall_time();
    return write_info(nb);
}

static void page_path(const NotebookInfo *nb, uint32_t pid, char *buf, size_t cap) {
    snprintf(buf, cap, "%s/notebooks/%s/p%u.qpg", g_root, nb->id, pid);
}

static int write_page_file(const NotebookInfo *nb, uint32_t pid, const Page *p) {
    uint8_t *data;
    size_t len;
    if (page_serialize(p, &data, &len) != 0) return -1;
    char path[700];
    page_path(nb, pid, path, sizeof path);
    int rc = write_file_atomic(path, data, len);
    free(data);
    return rc;
}

static void random_hex(char *out, int n) {
    uint8_t b[8] = {0};
    int fd = open("/dev/urandom", O_RDONLY);
    bool ok = fd >= 0 && read(fd, b, sizeof b) == (ssize_t)sizeof b;
    if (fd >= 0) close(fd);
    if (!ok) {
        uint32_t x = now_ms() ^ (uint32_t)getpid() * 2654435761u;
        memcpy(b, &x, sizeof x);
    }
    static const char hx[] = "0123456789abcdef";
    for (int i = 0; i < n; i++) out[i] = hx[(b[i / 2] >> ((i & 1) ? 0 : 4)) & 15];
    out[n] = 0;
}

int store_create(const char *name, const char *folder, PaperKind paper, NotebookInfo *out) {
    NotebookInfo *nb = out;
    memset(nb, 0, sizeof *nb);
    time_t t = (time_t)wall_time();
    struct tm tm;
    localtime_r(&t, &tm);
    char rnd[8];
    random_hex(rnd, 4);
    snprintf(nb->id, sizeof nb->id, "%04d%02d%02d-%02d%02d%02d-%s", tm.tm_year + 1900, tm.tm_mon + 1, tm.tm_mday,
             tm.tm_hour, tm.tm_min, tm.tm_sec, rnd);
    clean_line(nb->name, name && *name ? name : "Untitled", sizeof nb->name);
    clean_line(nb->folder, folder ? folder : "", sizeof nb->folder);
    nb->paper = paper_sanitize((uint32_t)paper, PAPER_MEDIUM);
    nb->created = nb->modified = (int64_t)t;
    nb->npages = 1;
    nb->page_ids[0] = 1;
    nb->next_page_id = 2;
    char dir[600], parent[600];
    snprintf(parent, sizeof parent, "%s/notebooks", g_root);
    if (mkdir_p(parent) != 0) return -1;
    // Two notebooks made in the same second must never share a directory: plain mkdir, and a
    // fresh random suffix if the name is taken.
    for (int attempt = 0;; attempt++) {
        store_notebook_dir(nb->id, dir, sizeof dir);
        if (mkdir(dir, 0755) == 0) break;
        if (errno != EEXIST || attempt >= 8) {
            qlog("store: cannot create %s: %s", dir, strerror(errno));
            return -1;
        }
        char rnd2[8];
        random_hex(rnd2, 4);
        memcpy(nb->id + strlen(nb->id) - 4, rnd2, 4);
    }
    Page *p = page_new(g_w, g_h, nb->paper);
    if (!p) return -1;
    int rc = write_page_file(nb, 1, p);
    page_free(p);
    if (rc != 0) return -1;
    return write_info(nb);
}

int store_rename(const char *id, const char *name) {
    NotebookInfo *nb = malloc(sizeof *nb);
    if (!nb) return -1;
    int rc = store_load_info(id, nb);
    if (rc == 0) {
        clean_line(nb->name, name, sizeof nb->name);
        rc = store_save_info(nb);
    }
    free(nb);
    return rc;
}

int store_set_folder(const char *id, const char *folder) {
    NotebookInfo *nb = malloc(sizeof *nb);
    if (!nb) return -1;
    int rc = store_load_info(id, nb);
    if (rc == 0) {
        clean_line(nb->folder, folder ? folder : "", sizeof nb->folder);
        rc = store_save_info(nb);
    }
    free(nb);
    return rc;
}

static int move_to_trash(const char *src, const char *base) {
    char dst[800];
    snprintf(dst, sizeof dst, "%s/trash/%s-%lld", g_root, base, (long long)wall_time());
    if (rename(src, dst) != 0) {
        qlog("trash %s: %s", src, strerror(errno));
        return -1;
    }
    return 0;
}

int store_delete(const char *id) {
    char dir[600];
    if (store_notebook_dir(id, dir, sizeof dir) != 0) return -1;
    return move_to_trash(dir, id);
}

static int cmp_modified(const void *a, const void *b) {
    const NotebookInfo *x = a, *y = b;
    if (x->modified != y->modified) return x->modified < y->modified ? 1 : -1;
    return strcmp(x->id, y->id);
}

int store_list(NotebookInfo **out, int *n) {
    *out = NULL;
    *n = 0;
    char dir[600];
    snprintf(dir, sizeof dir, "%s/notebooks", g_root);
    DIR *d = opendir(dir);
    if (!d) return -1;
    int cap = 0;
    NotebookInfo *arr = NULL;
    struct dirent *e;
    while ((e = readdir(d))) {
        if (e->d_name[0] == '.' || !id_ok(e->d_name)) continue;
        if (*n == cap) {
            int nc = cap ? cap * 2 : 16;
            NotebookInfo *na = realloc(arr, (size_t)nc * sizeof *na);
            if (!na) break;
            arr = na;
            cap = nc;
        }
        if (store_load_info(e->d_name, &arr[*n]) == 0) (*n)++;
        else qlog("store: skipping unreadable notebook %s", e->d_name);
    }
    closedir(d);
    if (*n) qsort(arr, (size_t)*n, sizeof *arr, cmp_modified);
    *out = arr;
    return 0;
}

// ---- folders ----

typedef char FolderName[STORE_NAME_LEN];

static int load_folders_ini(FolderName **out, int *n) {
    char path[600];
    snprintf(path, sizeof path, "%s/folders.ini", g_root);
    *out = NULL;
    *n = 0;
    size_t len;
    char *txt = read_file(path, &len);
    if (!txt) return 0;
    int cap = 0;
    char *save = NULL;
    bool first = true;
    for (char *line = strtok_r(txt, "\n", &save); line; line = strtok_r(NULL, "\n", &save)) {
        // Only the header line is a comment: a folder may well be called "#1".
        bool header = first && !strncmp(line, "# ", 2) && strstr(line, " folders");
        first = false;
        if (!*line || header) continue;
        if (*n == cap) {
            int nc = cap ? cap * 2 : 8;
            FolderName *na = realloc(*out, (size_t)nc * sizeof *na);
            if (!na) break;
            *out = na;
            cap = nc;
        }
        clean_line((*out)[(*n)++], line, STORE_NAME_LEN);
    }
    free(txt);
    return 0;
}

static int save_folders_ini(FolderName *f, int n) {
    char path[600];
    snprintf(path, sizeof path, "%s/folders.ini", g_root);
    size_t cap = 32 + (size_t)n * STORE_NAME_LEN;
    char *buf = malloc(cap);
    if (!buf) return -1;
    size_t len = (size_t)snprintf(buf, cap, "# Grimoire folders\n");
    for (int i = 0; i < n; i++) len += (size_t)snprintf(buf + len, cap - len, "%s\n", f[i]);
    int rc = write_file_atomic(path, buf, len);
    free(buf);
    return rc;
}

int store_add_folder(const char *name) {
    if (!name || !*name) return -1;
    FolderName *f;
    int n;
    load_folders_ini(&f, &n);
    for (int i = 0; i < n; i++)
        if (!strcmp(f[i], name)) {
            free(f);
            return 0;
        }
    FolderName *nf = realloc(f, (size_t)(n + 1) * sizeof *nf);
    if (!nf) {
        free(f);
        return -1;
    }
    clean_line(nf[n], name, STORE_NAME_LEN);
    int rc = save_folders_ini(nf, n + 1);
    free(nf);
    return rc;
}

int store_remove_folder(const char *name) {
    FolderName *f;
    int n;
    load_folders_ini(&f, &n);
    int m = 0;
    for (int i = 0; i < n; i++)
        if (strcmp(f[i], name)) memmove(f[m++], f[i], STORE_NAME_LEN);
    int rc = save_folders_ini(f, m);
    free(f);
    return rc;
}

static int cmp_name(const void *a, const void *b) { return strcasecmp(a, b); }

int store_list_folders(char (**out)[STORE_NAME_LEN], int *n) {
    FolderName *f;
    int nf;
    load_folders_ini(&f, &nf);
    NotebookInfo *nbs;
    int nn;
    store_list(&nbs, &nn);
    FolderName *all = malloc((size_t)(nf + nn + 1) * sizeof *all);
    *out = NULL;
    *n = 0;
    if (!all) {
        free(f);
        free(nbs);
        return -1;
    }
    int m = 0;
    for (int i = 0; i < nf + nn; i++) {
        const char *name = i < nf ? f[i] : nbs[i - nf].folder;
        if (!*name) continue;
        bool dup = false;
        for (int k = 0; k < m && !dup; k++) dup = !strcmp(all[k], name);
        if (!dup) strlcpy_q(all[m++], name, STORE_NAME_LEN);
    }
    free(f);
    free(nbs);
    qsort(all, (size_t)m, sizeof *all, cmp_name);
    *out = all;
    *n = m;
    return 0;
}

// ---- pages ----

int store_add_page(NotebookInfo *nb, int at, PaperKind paper) {
    if (nb->npages >= STORE_MAX_PAGES) return -1;
    at = clampi(at, 0, nb->npages);
    uint32_t pid = nb->next_page_id++;
    Page *p = page_new(g_w, g_h, paper);
    if (!p) return -1;
    int rc = write_page_file(nb, pid, p);
    page_free(p);
    if (rc != 0) return -1;
    memmove(&nb->page_ids[at + 1], &nb->page_ids[at], (size_t)(nb->npages - at) * sizeof nb->page_ids[0]);
    nb->page_ids[at] = pid;
    nb->npages++;
    return store_save_info(nb);
}

int store_delete_page(NotebookInfo *nb, int index) {
    if (nb->npages <= 1 || index < 0 || index >= nb->npages) return -1;
    char path[700], base[80];
    page_path(nb, nb->page_ids[index], path, sizeof path);
    snprintf(base, sizeof base, "%s-p%u", nb->id, nb->page_ids[index]);
    if (access(path, F_OK) == 0) move_to_trash(path, base);
    memmove(&nb->page_ids[index], &nb->page_ids[index + 1], (size_t)(nb->npages - index - 1) * sizeof nb->page_ids[0]);
    nb->npages--;
    nb->last_page = clampi(nb->last_page, 0, nb->npages - 1);
    return store_save_info(nb);
}

static void scale_page(Page *p, int w, int h) {
    if (p->w == w && p->h == h) return;
    float sx = (float)w / (float)p->w, sy = (float)h / (float)p->h;
    for (int i = 0; i < p->n; i++) {
        Stroke *s = p->strokes[i];
        int n = s->n;
        PenSample *pts = s->pts;
        s->pts = NULL;
        s->n = s->cap = 0;
        s->bbox = RECT_EMPTY;
        for (int k = 0; k < n; k++) {
            pts[k].x *= sx;
            pts[k].y *= sy;
            stroke_append(s, &pts[k], g_dpi);
        }
        free(pts);
    }
    p->w = w;
    p->h = h;
}

int store_load_page(const NotebookInfo *nb, int index, int w, int h, Page **out) {
    *out = NULL;
    if (index < 0 || index >= nb->npages) return -1;
    char path[700];
    page_path(nb, nb->page_ids[index], path, sizeof path);
    size_t len;
    uint8_t *data = read_file(path, &len);
    Page *p = NULL;
    if (data) {
        if (page_deserialize(data, len, &p) != 0) {
            // Keep the damaged file instead of letting the next autosave replace it with the
            // blank page shown in its place. (A page from a newer version is not damage: it
            // opens read-only.)
            char aside[760];
            snprintf(aside, sizeof aside, "%s.damaged-%lld", path, (long long)wall_time());
            int rc = rename(path, aside);
            qlog("store: corrupt page %s, %s; starting blank", path, rc == 0 ? "set aside" : "could not set aside");
            g_corrupt_pages++;
        } else if (p->readonly) {
            qlog("store: %s opens read-only and stays as it is on disk", path);
        }
        free(data);
    }
    if (!p) p = page_new(w, h, nb->paper);
    if (!p) return -1;
    scale_page(p, w, h);
    *out = p;
    return 0;
}

int store_save_page(const NotebookInfo *nb, int index, const Page *p) {
    if (index < 0 || index >= nb->npages) return -1;
    // A read-only page stays as it is on disk: writing it would lose what this build cannot read.
    if (p->readonly) return 0;
    return write_page_file(nb, nb->page_ids[index], p);
}

// ---- pages 1.0.0-beta set aside ----

typedef struct {
    uint32_t pid;
    long long t;
    char name[64];
} Aside;

static int cmp_aside(const void *a, const void *b) {
    const Aside *x = a, *y = b;
    if (x->pid != y->pid) return x->pid < y->pid ? -1 : 1;
    return x->t < y->t ? 1 : x->t > y->t ? -1 : 0;  // newest first
}

static bool page_file_opens(const char *path) {
    size_t len;
    uint8_t *data = read_file(path, &len);
    Page *p = NULL;
    bool ok = data && page_deserialize(data, len, &p) == 0;
    page_free(p);
    free(data);
    return ok;
}

int store_recover_pages(const NotebookInfo *nb) {
    char dir[600];
    if (store_notebook_dir(nb->id, dir, sizeof dir) != 0) return 0;
    DIR *d = opendir(dir);
    if (!d) return 0;
    Aside *as = NULL;
    int n = 0, cap = 0;
    struct dirent *e;
    while ((e = readdir(d))) {
        unsigned long id;
        long long t;
        int end = 0;
        if (sscanf(e->d_name, "p%lu.qpg.damaged-%lld%n", &id, &t, &end) != 2 || e->d_name[end] || id == 0 ||
            id >= 0x7fffffff || strlen(e->d_name) >= sizeof as->name)
            continue;
        if (n == cap) {
            int nc = cap ? cap * 2 : 8;
            Aside *na = realloc(as, (size_t)nc * sizeof *na);
            if (!na) break;
            as = na;
            cap = nc;
        }
        as[n].pid = (uint32_t)id;
        as[n].t = t;
        strlcpy_q(as[n].name, e->d_name, sizeof as[n].name);
        n++;
    }
    closedir(d);
    if (n) qsort(as, (size_t)n, sizeof *as, cmp_aside);
    int restored = 0;
    for (int i = 0; i < n;) {
        int j = i;
        while (j < n && as[j].pid == as[i].pid) j++;
        char path[700], aside[760];
        snprintf(path, sizeof path, "%s/p%u.qpg", dir, as[i].pid);
        bool exists = access(path, F_OK) == 0;
        // The newest copy that opens now, normally or read-only; real damage stays aside.
        for (int k = i; k < j; k++) {
            snprintf(aside, sizeof aside, "%s/%s", dir, as[k].name);
            if (!page_file_opens(aside)) continue;
            if (exists) {
                // An older version wrote a fresh page there since (it was edited): keep both.
                qlog("store: %s: %s opens now, but p%u.qpg exists too; both kept", nb->id, as[k].name, as[k].pid);
            } else if (rename(aside, path) == 0) {
                bool listed = false;
                for (int q = 0; q < nb->npages && !listed; q++) listed = nb->page_ids[q] == as[k].pid;
                qlog("store: %s: recovered p%u.qpg from %s%s", nb->id, as[k].pid, as[k].name,
                     listed ? "" : " (not in the page list)");
                restored++;
            } else {
                qlog("store: %s: could not recover %s: %s", nb->id, as[k].name, strerror(errno));
            }
            break;
        }
        i = j;
    }
    free(as);
    return restored;
}

// ---- page format ----

typedef struct {
    uint8_t *d;
    size_t n, cap;
    bool err;
} W;

static void w_bytes(W *w, const void *p, size_t n) {
    if (w->err) return;
    if (w->n + n > w->cap) {
        size_t nc = w->cap ? w->cap * 2 : 4096;
        while (nc < w->n + n) nc *= 2;
        uint8_t *nd = realloc(w->d, nc);
        if (!nd) {
            w->err = true;
            return;
        }
        w->d = nd;
        w->cap = nc;
    }
    memcpy(w->d + w->n, p, n);
    w->n += n;
}
static void w_u8(W *w, uint8_t v) { w_bytes(w, &v, 1); }
static void w_u16(W *w, uint16_t v) {
    uint8_t b[2] = {(uint8_t)v, (uint8_t)(v >> 8)};
    w_bytes(w, b, 2);
}
static void w_u32(W *w, uint32_t v) {
    uint8_t b[4] = {(uint8_t)v, (uint8_t)(v >> 8), (uint8_t)(v >> 16), (uint8_t)(v >> 24)};
    w_bytes(w, b, 4);
}
static void w_f32(W *w, float f) {
    uint32_t u;
    memcpy(&u, &f, 4);
    w_u32(w, u);
}

// The fixed paper kinds 1.0.0-beta knows (its PAPER_COUNT). Pages on one of them are version 1;
// any other kind is version 2 (docs/FORMAT.md). Never changes, even when kinds are added.
#define PAGE_V1_PAPERS 17u
// Versions a newer Grimoire may write (3 and up, staying below 256): such a page opens read-only.
// Anything else (0, or a number no version uses) is damage.
#define PAGE_NEWER_MAX 255u

int page_serialize(const Page *p, uint8_t **out, size_t *len) {
    // A page this build cannot fully read would lose what it cannot read: it is never written.
    if (p->readonly) return -1;
    W w = {0};
    // Version 2 only when the paper needs all 32 bits (custom music, or a paper from a newer
    // version): other pages stay version 1, as 1.0.0-beta writes them. In version 2 the u16 says
    // PAPER_MUSIC for custom music, as it always did, and PAPER_BLANK for any other kind.
    bool v2 = (uint32_t)p->paper >= PAGE_V1_PAPERS;
    PaperKind p16 = !v2 ? p->paper : paper_is_custom(p->paper) ? PAPER_MUSIC : PAPER_BLANK;
    w_bytes(&w, "QPG1", 4);
    w_u16(&w, v2 ? 2 : 1);
    w_u16(&w, (uint16_t)p16);
    w_u32(&w, (uint32_t)p->w);
    w_u32(&w, (uint32_t)p->h);
    if (v2) w_u32(&w, (uint32_t)p->paper);
    w_u32(&w, (uint32_t)p->n);
    for (int i = 0; i < p->n; i++) {
        const Stroke *s = p->strokes[i];
        w_u8(&w, (uint8_t)s->tool);
        w_bytes(&w, s->ext, 3);  // as read (0 for strokes drawn here)
        w_u32(&w, s->seed);
        const float *f = (const float *)&s->params;
        for (int k = 0; k < 13; k++) w_f32(&w, f[k]);
        w_u32(&w, (uint32_t)s->n);
        for (int k = 0; k < s->n; k++) {
            const PenSample *q = &s->pts[k];
            w_f32(&w, q->x);
            w_f32(&w, q->y);
            w_u16(&w, (uint16_t)lrintf(clampf(q->pressure, 0.f, 1.f) * 65535.f));
            w_u16(&w, (uint16_t)(int16_t)lrintf(clampf(q->tilt_x, -90.f, 90.f) * 100.f));
            w_u16(&w, (uint16_t)(int16_t)lrintf(clampf(q->tilt_y, -90.f, 90.f) * 100.f));
            w_u32(&w, q->t_ms);
        }
    }
    // The chunks that followed the strokes, as they were read (this version writes none itself).
    if (p->tail_len) w_bytes(&w, p->tail, p->tail_len);
    if (w.err) {
        free(w.d);
        return -1;
    }
    *out = w.d;
    *len = w.n;
    return 0;
}

typedef struct {
    const uint8_t *d;
    size_t n, pos;
    bool err;
} R;

static const uint8_t *r_take(R *r, size_t n) {
    if (r->err || r->n - r->pos < n) {
        r->err = true;
        return NULL;
    }
    const uint8_t *p = r->d + r->pos;
    r->pos += n;
    return p;
}
static uint8_t r_u8(R *r) {
    const uint8_t *p = r_take(r, 1);
    return p ? p[0] : 0;
}
static uint16_t r_u16(R *r) {
    const uint8_t *p = r_take(r, 2);
    return p ? (uint16_t)(p[0] | p[1] << 8) : 0;
}
static uint32_t r_u32(R *r) {
    const uint8_t *p = r_take(r, 4);
    return p ? (uint32_t)p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24 : 0;
}
static float r_f32(R *r) {
    uint32_t u = r_u32(r);
    float f;
    memcpy(&f, &u, 4);
    return isfinite(f) ? f : 0.f;
}

#define STROKE_HEADER_BYTES (4 + 4 + 13 * 4 + 4)
#define POINT_BYTES (4 + 4 + 2 + 2 + 2 + 4)

static bool sane_size(uint32_t w, uint32_t h) { return w > 0 && h > 0 && w <= 20000 && h <= 20000; }

// A page from a newer version: only the 16 bytes every version starts with are read (magic,
// version, u16 paper, w, h). It is shown blank, read-only.
static int newer_page(unsigned ver, uint32_t w, uint32_t h, Page **out) {
    bool sane = sane_size(w, h);
    Page *p = page_new(sane ? (int)w : g_w, sane ? (int)h : g_h, PAPER_BLANK);
    if (!p) return -1;
    p->readonly = true;
    qlog("store: read-only page: version %u is from a newer Grimoire, shown blank", ver);
    *out = p;
    return 0;
}

static bool tag_char(uint8_t c, bool first) {
    return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (!first && c >= '0' && c <= '9');
}

// The chunks after the last stroke, to the end of the file: u32 tag (four ASCII letters or digits,
// the first a letter), u32 length, the bytes. This version knows no chunk. One whose tag starts
// with a lowercase letter is safe to copy: carried, written back as it was. One starting with an
// uppercase letter is critical, and like bytes that are not chunks, makes the page read-only.
// The whole tail is kept either way. Returns why the page is read-only, or NULL.
static const char *read_tail(R *r, Page *p, char *why, size_t cap) {
    if (r->pos >= r->n) return NULL;
    size_t tl = r->n - r->pos;
    p->tail = malloc(tl);
    if (!p->tail) return "no memory for its chunks";
    memcpy(p->tail, r->d + r->pos, tl);
    p->tail_len = tl;
    while (r->pos < r->n) {
        const uint8_t *c = r->d + r->pos;
        if (r->n - r->pos < 8) return "cut-off bytes after the strokes";
        bool ok = tag_char(c[0], true) && tag_char(c[1], false) && tag_char(c[2], false) && tag_char(c[3], false);
        if (!ok) return "bytes after the strokes that are not chunks";
        uint32_t clen = (uint32_t)c[4] | (uint32_t)c[5] << 8 | (uint32_t)c[6] << 16 | (uint32_t)c[7] << 24;
        if (clen > r->n - r->pos - 8) return "a chunk longer than the file";
        if (c[0] >= 'A' && c[0] <= 'Z') {
            snprintf(why, cap, "a chunk this version does not know (%.4s)", (const char *)c);
            return why;
        }
        r->pos += 8 + (size_t)clen;
    }
    return NULL;
}

int page_deserialize(const uint8_t *buf, size_t len, Page **out) {
    *out = NULL;
    R r = {buf, len, 0, false};
    const uint8_t *m = r_take(&r, 4);
    if (!m || memcmp(m, "QPG1", 4) != 0) return -1;
    uint16_t ver = r_u16(&r);
    uint32_t paper = r_u16(&r);
    uint32_t w = r_u32(&r), h = r_u32(&r);
    if (r.err) return -1;
    if (ver > 2 && ver <= PAGE_NEWER_MAX) return newer_page(ver, w, h, out);
    if (ver != 1 && ver != 2) return -1;
    if (ver == 2) paper = r_u32(&r);
    uint32_t ns = r_u32(&r);
    if (r.err || !sane_size(w, h)) return -1;
    if (ns > (len - r.pos) / STROKE_HEADER_BYTES) return -1;
    // A paper this build does not know stays as it is: drawn blank, written back.
    Page *p = page_new((int)w, (int)h, (PaperKind)paper);
    if (!p) return -1;
    uint32_t unknown_tools = 0;
    for (uint32_t i = 0; i < ns && !r.err; i++) {
        uint8_t tool = r_u8(&r);
        const uint8_t *ext = r_take(&r, 3);
        uint32_t seed = r_u32(&r);
        ToolParams prm;
        float *f = (float *)&prm;
        for (int k = 0; k < 13; k++) f[k] = r_f32(&r);
        uint32_t np = r_u32(&r);
        if (r.err || np > (len - r.pos) / POINT_BYTES) {
            r.err = true;
            break;
        }
        if (tool >= TOOL_COUNT) {
            // A newer version's tool: the record is laid out the same, so the page reads on.
            // The stroke is left out (never drawn) and the page becomes read-only, so no save
            // here can drop it.
            r_take(&r, (size_t)np * POINT_BYTES);
            unknown_tools++;
            continue;
        }
        // Clamp params into their UI ranges so a hostile file cannot make huge dabs.
        int npi;
        const ParamInfo *pi = tool_param_table(&npi);
        for (int k = 0; k < npi; k++) {
            float *v = tool_param_ptr(&prm, &pi[k]);
            *v = clampf(*v, pi[k].min, pi[k].max);
        }
        Stroke *s = stroke_new((ToolKind)tool, &prm, seed);
        if (!s) {
            r.err = true;
            break;
        }
        memcpy(s->ext, ext, 3);
        for (uint32_t k = 0; k < np; k++) {
            PenSample q;
            q.x = clampf(r_f32(&r), -10000.f, 30000.f);
            q.y = clampf(r_f32(&r), -10000.f, 30000.f);
            q.pressure = (float)r_u16(&r) / 65535.f;
            q.tilt_x = (float)(int16_t)r_u16(&r) / 100.f;
            q.tilt_y = (float)(int16_t)r_u16(&r) / 100.f;
            q.t_ms = r_u32(&r);
            stroke_append(s, &q, g_dpi);
        }
        page_add(p, s);
    }
    if (r.err) {
        page_free(p);
        return -1;
    }
    char why[96];
    const char *ro = read_tail(&r, p, why, sizeof why);
    if (unknown_tools) {
        snprintf(why, sizeof why, "%u stroke%s with a tool this version does not have", unknown_tools,
                 unknown_tools == 1 ? "" : "s");
        ro = why;
    }
    if (ro) {
        p->readonly = true;
        qlog("store: read-only page: %s", ro);
    }
    *out = p;
    return 0;
}

