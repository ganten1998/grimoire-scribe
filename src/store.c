static char g_root[512];
static float g_dpi = 300.f;
static int g_w = 1860, g_h = 2480;

void store_set_device(float dpi, int w, int h) {
    if (dpi > 50.f) g_dpi = dpi;
    if (w > 0) g_w = w;
    if (h > 0) g_h = h;
}
float store_dpi(void) { return g_dpi; }
void store_page_size(int *w, int *h) {
    *w = g_w;
    *h = g_h;
}
const char *store_root(void) { return g_root; }

int store_init(const char *root) {
    strlcpy_q(g_root, root, sizeof g_root);
    char p[600];
    if (mkdir_p(root) != 0) {
        qlog("store: cannot create %s", root);
        return -1;
    }
    snprintf(p, sizeof p, "%s/notebooks", root);
    mkdir_p(p);
    snprintf(p, sizeof p, "%s/trash", root);
    mkdir_p(p);
    return 0;
}

// Ids are generated by us; reject anything that could escape the notebooks dir.
static bool id_ok(const char *id) {
    if (!id || !*id || strlen(id) >= STORE_ID_LEN) return false;
    for (const char *c = id; *c; c++)
        if (!((*c >= '0' && *c <= '9') || (*c >= 'a' && *c <= 'z') || (*c >= 'A' && *c <= 'Z') || *c == '-' ||
              *c == '_'))
            return false;
    return true;
}

int store_notebook_dir(const char *id, char *buf, size_t cap) {
    if (!id_ok(id)) return -1;
    snprintf(buf, cap, "%s/notebooks/%s", g_root, id);
    return 0;
}

// ---- tiny ini ----

typedef void (*IniCb)(void *ctx, const char *key, const char *val);

static int ini_parse_file(const char *path, IniCb cb, void *ctx) {
    size_t len;
    char *txt = read_file(path, &len);
    if (!txt) return -1;
    char *save = NULL;
    for (char *line = strtok_r(txt, "\n", &save); line; line = strtok_r(NULL, "\n", &save)) {
        char *eq = strchr(line, '=');
        if (!eq || line[0] == '#') continue;
        *eq = 0;
        char *v = eq + 1;
        size_t vl = strlen(v);
        if (vl && v[vl - 1] == '\r') v[vl - 1] = 0;
        cb(ctx, line, v);
    }
    free(txt);
    return 0;
}

// Names are single-line in the ini.
static void clean_line(char *dst, const char *src, size_t cap) {
    size_t n = strlcpy_q(dst, src, cap);
    for (size_t i = 0; i < n; i++)
        if (dst[i] == '\n' || dst[i] == '\r') dst[i] = ' ';
}

// ---- notebooks ----

static void info_cb(void *ctx, const char *k, const char *v) {
    NotebookInfo *nb = ctx;
    if (!strcmp(k, "name")) clean_line(nb->name, v, sizeof nb->name);
    else if (!strcmp(k, "folder")) clean_line(nb->folder, v, sizeof nb->folder);
    else if (!strcmp(k, "paper")) nb->paper = (PaperKind)clampi(atoi(v), 0, PAPER_COUNT - 1);
    else if (!strcmp(k, "created")) nb->created = atoll(v);
    else if (!strcmp(k, "modified")) nb->modified = atoll(v);
    else if (!strcmp(k, "last_page")) nb->last_page = atoi(v);
    else if (!strcmp(k, "next_page_id")) nb->next_page_id = (uint32_t)strtoul(v, NULL, 10);
    else if (!strcmp(k, "pages")) {
        nb->npages = 0;
        const char *p = v;
        while (*p && nb->npages < STORE_MAX_PAGES) {
            char *end;
            unsigned long id = strtoul(p, &end, 10);
            if (end == p) break;
            if (id > 0) nb->page_ids[nb->npages++] = (uint32_t)id;
            p = *end == ',' ? end + 1 : end;
        }
    }
}

int store_load_info(const char *id, NotebookInfo *out) {
    char dir[600], path[700];
    if (store_notebook_dir(id, dir, sizeof dir) != 0) return -1;
    memset(out, 0, sizeof *out);
    strlcpy_q(out->id, id, sizeof out->id);
    snprintf(path, sizeof path, "%s/notebook.ini", dir);
    if (ini_parse_file(path, info_cb, out) != 0) return -1;
    if (out->npages == 0) {  // never leave a notebook without a page
        out->page_ids[0] = 1;
        out->npages = 1;
    }
    uint32_t maxid = 0;
    for (int i = 0; i < out->npages; i++)
        if (out->page_ids[i] > maxid) maxid = out->page_ids[i];
    if (out->next_page_id <= maxid) out->next_page_id = maxid + 1;
    out->last_page = clampi(out->last_page, 0, out->npages - 1);
    if (!out->name[0]) strlcpy_q(out->name, "Untitled", sizeof out->name);
    return 0;
}

static int write_info(const NotebookInfo *nb) {
    char dir[600], path[700];
    if (store_notebook_dir(nb->id, dir, sizeof dir) != 0) return -1;
    snprintf(path, sizeof path, "%s/notebook.ini", dir);
    size_t cap = 1024 + (size_t)nb->npages * 12;
    char *buf = malloc(cap);
    if (!buf) return -1;
    char name[STORE_NAME_LEN], folder[STORE_NAME_LEN];
    clean_line(name, nb->name, sizeof name);
    clean_line(folder, nb->folder, sizeof folder);
    int n = snprintf(buf, cap,
                     "# Quire notebook\nname=%s\nfolder=%s\npaper=%d\ncreated=%lld\nmodified=%lld\n"
                     "last_page=%d\nnext_page_id=%u\npages=",
                     name, folder, (int)nb->paper, (long long)nb->created, (long long)nb->modified, nb->last_page,
                     nb->next_page_id);
    for (int i = 0; i < nb->npages && (size_t)n < cap - 16; i++)
        n += snprintf(buf + n, cap - (size_t)n, "%s%u", i ? "," : "", nb->page_ids[i]);
    n += snprintf(buf + n, cap - (size_t)n, "\n");
    int rc = write_file_atomic(path, buf, (size_t)n);
    free(buf);
    return rc;
}

int store_save_info(NotebookInfo *nb) {
    nb->modified = wall_time();
    return write_info(nb);
}

static void page_path(const NotebookInfo *nb, uint32_t pid, char *buf, size_t cap) {
    snprintf(buf, cap, "%s/notebooks/%s/p%u.qpg", g_root, nb->id, pid);
}

static int write_page_file(const NotebookInfo *nb, uint32_t pid, const Page *p) {
    uint8_t *data;
    size_t len;
    if (page_serialize(p, &data, &len) != 0) return -1;
    char path[700];
    page_path(nb, pid, path, sizeof path);
    int rc = write_file_atomic(path, data, len);
    free(data);
    return rc;
}

static void random_hex(char *out, int n) {
    uint8_t b[8] = {0};
    int fd = open("/dev/urandom", O_RDONLY);
    bool ok = fd >= 0 && read(fd, b, sizeof b) == (ssize_t)sizeof b;
    if (fd >= 0) close(fd);
    if (!ok) {
        uint32_t x = now_ms() ^ (uint32_t)getpid() * 2654435761u;
        memcpy(b, &x, sizeof x);
    }
    static const char hx[] = "0123456789abcdef";
    for (int i = 0; i < n; i++) out[i] = hx[(b[i / 2] >> ((i & 1) ? 0 : 4)) & 15];
    out[n] = 0;
}

int store_create(const char *name, const char *folder, PaperKind paper, NotebookInfo *out) {
    NotebookInfo *nb = out;
    memset(nb, 0, sizeof *nb);
    time_t t = (time_t)wall_time();
    struct tm tm;
    localtime_r(&t, &tm);
    char rnd[8];
    random_hex(rnd, 4);
    snprintf(nb->id, sizeof nb->id, "%04d%02d%02d-%02d%02d%02d-%s", tm.tm_year + 1900, tm.tm_mon + 1, tm.tm_mday,
             tm.tm_hour, tm.tm_min, tm.tm_sec, rnd);
    clean_line(nb->name, name && *name ? name : "Untitled", sizeof nb->name);
    clean_line(nb->folder, folder ? folder : "", sizeof nb->folder);
    nb->paper = (paper >= 0 && paper < PAPER_COUNT) ? paper : PAPER_MEDIUM;
    nb->created = nb->modified = (int64_t)t;
    nb->npages = 1;
    nb->page_ids[0] = 1;
    nb->next_page_id = 2;
    char dir[600];
    store_notebook_dir(nb->id, dir, sizeof dir);
    if (mkdir_p(dir) != 0) return -1;
    Page *p = page_new(g_w, g_h, nb->paper);
    if (!p) return -1;
    int rc = write_page_file(nb, 1, p);
    page_free(p);
    if (rc != 0) return -1;
    return write_info(nb);
}

int store_rename(const char *id, const char *name) {
    NotebookInfo *nb = malloc(sizeof *nb);
    if (!nb) return -1;
    int rc = store_load_info(id, nb);
    if (rc == 0) {
        clean_line(nb->name, name, sizeof nb->name);
        rc = store_save_info(nb);
    }
    free(nb);
    return rc;
}

int store_set_folder(const char *id, const char *folder) {
    NotebookInfo *nb = malloc(sizeof *nb);
    if (!nb) return -1;
    int rc = store_load_info(id, nb);
    if (rc == 0) {
        clean_line(nb->folder, folder ? folder : "", sizeof nb->folder);
        rc = store_save_info(nb);
    }
    free(nb);
    return rc;
}

static int move_to_trash(const char *src, const char *base) {
    char dst[800];
    snprintf(dst, sizeof dst, "%s/trash/%s-%lld", g_root, base, (long long)wall_time());
    if (rename(src, dst) != 0) {
        qlog("trash %s: %s", src, strerror(errno));
        return -1;
    }
    return 0;
}

int store_delete(const char *id) {
    char dir[600];
    if (store_notebook_dir(id, dir, sizeof dir) != 0) return -1;
    return move_to_trash(dir, id);
}

static int cmp_modified(const void *a, const void *b) {
    const NotebookInfo *x = a, *y = b;
    if (x->modified != y->modified) return x->modified < y->modified ? 1 : -1;
    return strcmp(x->id, y->id);
}

int store_list(NotebookInfo **out, int *n) {
    *out = NULL;
    *n = 0;
    char dir[600];
    snprintf(dir, sizeof dir, "%s/notebooks", g_root);
    DIR *d = opendir(dir);
    if (!d) return -1;
    int cap = 0;
    NotebookInfo *arr = NULL;
    struct dirent *e;
    while ((e = readdir(d))) {
        if (e->d_name[0] == '.' || !id_ok(e->d_name)) continue;
        if (*n == cap) {
            int nc = cap ? cap * 2 : 16;
            NotebookInfo *na = realloc(arr, (size_t)nc * sizeof *na);
            if (!na) break;
            arr = na;
            cap = nc;
        }
        if (store_load_info(e->d_name, &arr[*n]) == 0) (*n)++;
        else qlog("store: skipping unreadable notebook %s", e->d_name);
    }
    closedir(d);
    if (*n) qsort(arr, (size_t)*n, sizeof *arr, cmp_modified);
    *out = arr;
    return 0;
}

// ---- folders ----

typedef char FolderName[STORE_NAME_LEN];

static int load_folders_ini(FolderName **out, int *n) {
    char path[600];
    snprintf(path, sizeof path, "%s/folders.ini", g_root);
    *out = NULL;
    *n = 0;
    size_t len;
    char *txt = read_file(path, &len);
    if (!txt) return 0;
    int cap = 0;
    char *save = NULL;
    for (char *line = strtok_r(txt, "\n", &save); line; line = strtok_r(NULL, "\n", &save)) {
        if (!*line || line[0] == '#') continue;
        if (*n == cap) {
            int nc = cap ? cap * 2 : 8;
            FolderName *na = realloc(*out, (size_t)nc * sizeof *na);
            if (!na) break;
            *out = na;
            cap = nc;
        }
        clean_line((*out)[(*n)++], line, STORE_NAME_LEN);
    }
    free(txt);
    return 0;
}

static int save_folders_ini(FolderName *f, int n) {
    char path[600];
    snprintf(path, sizeof path, "%s/folders.ini", g_root);
    size_t cap = 32 + (size_t)n * STORE_NAME_LEN;
    char *buf = malloc(cap);
    if (!buf) return -1;
    size_t len = (size_t)snprintf(buf, cap, "# Quire folders\n");
    for (int i = 0; i < n; i++) len += (size_t)snprintf(buf + len, cap - len, "%s\n", f[i]);
    int rc = write_file_atomic(path, buf, len);
    free(buf);
    return rc;
}

int store_add_folder(const char *name) {
    if (!name || !*name) return -1;
    FolderName *f;
    int n;
    load_folders_ini(&f, &n);
    for (int i = 0; i < n; i++)
        if (!strcmp(f[i], name)) {
            free(f);
            return 0;
        }
    FolderName *nf = realloc(f, (size_t)(n + 1) * sizeof *nf);
    if (!nf) {
        free(f);
        return -1;
    }
    clean_line(nf[n], name, STORE_NAME_LEN);
    int rc = save_folders_ini(nf, n + 1);
    free(nf);
    return rc;
}

int store_remove_folder(const char *name) {
    FolderName *f;
    int n;
    load_folders_ini(&f, &n);
    int m = 0;
    for (int i = 0; i < n; i++)
        if (strcmp(f[i], name)) memmove(f[m++], f[i], STORE_NAME_LEN);
    int rc = save_folders_ini(f, m);
    free(f);
    return rc;
}

static int cmp_name(const void *a, const void *b) { return strcasecmp(a, b); }

int store_list_folders(char (**out)[STORE_NAME_LEN], int *n) {
    FolderName *f;
    int nf;
    load_folders_ini(&f, &nf);
    NotebookInfo *nbs;
    int nn;
    store_list(&nbs, &nn);
    FolderName *all = malloc((size_t)(nf + nn + 1) * sizeof *all);
    *out = NULL;
    *n = 0;
    if (!all) {
        free(f);
        free(nbs);
        return -1;
    }
    int m = 0;
    for (int i = 0; i < nf + nn; i++) {
        const char *name = i < nf ? f[i] : nbs[i - nf].folder;
        if (!*name) continue;
        bool dup = false;
        for (int k = 0; k < m && !dup; k++) dup = !strcmp(all[k], name);
        if (!dup) strlcpy_q(all[m++], name, STORE_NAME_LEN);
    }
    free(f);
    free(nbs);
    qsort(all, (size_t)m, sizeof *all, cmp_name);
    *out = all;
    *n = m;
    return 0;
}

// ---- pages ----

int store_add_page(NotebookInfo *nb, int at, PaperKind paper) {
    if (nb->npages >= STORE_MAX_PAGES) return -1;
    at = clampi(at, 0, nb->npages);
    uint32_t pid = nb->next_page_id++;
    Page *p = page_new(g_w, g_h, paper);
    if (!p) return -1;
    int rc = write_page_file(nb, pid, p);
    page_free(p);
    if (rc != 0) return -1;
    memmove(&nb->page_ids[at + 1], &nb->page_ids[at], (size_t)(nb->npages - at) * sizeof nb->page_ids[0]);
    nb->page_ids[at] = pid;
    nb->npages++;
    return store_save_info(nb);
}

int store_delete_page(NotebookInfo *nb, int index) {
    if (nb->npages <= 1 || index < 0 || index >= nb->npages) return -1;
    char path[700], base[80];
    page_path(nb, nb->page_ids[index], path, sizeof path);
    snprintf(base, sizeof base, "%s-p%u", nb->id, nb->page_ids[index]);
    if (access(path, F_OK) == 0) move_to_trash(path, base);
    memmove(&nb->page_ids[index], &nb->page_ids[index + 1], (size_t)(nb->npages - index - 1) * sizeof nb->page_ids[0]);
    nb->npages--;
    nb->last_page = clampi(nb->last_page, 0, nb->npages - 1);
    return store_save_info(nb);
}

static void scale_page(Page *p, int w, int h) {
    if (p->w == w && p->h == h) return;
    float sx = (float)w / (float)p->w, sy = (float)h / (float)p->h;
    for (int i = 0; i < p->n; i++) {
        Stroke *s = p->strokes[i];
        int n = s->n;
        PenSample *pts = s->pts;
        s->pts = NULL;
        s->n = s->cap = 0;
        s->bbox = RECT_EMPTY;
        for (int k = 0; k < n; k++) {
            pts[k].x *= sx;
            pts[k].y *= sy;
            stroke_append(s, &pts[k], g_dpi);
        }
        free(pts);
    }
    p->w = w;
    p->h = h;
}

int store_load_page(const NotebookInfo *nb, int index, int w, int h, Page **out) {
    *out = NULL;
    if (index < 0 || index >= nb->npages) return -1;
    char path[700];
    page_path(nb, nb->page_ids[index], path, sizeof path);
    size_t len;
    uint8_t *data = read_file(path, &len);
    Page *p = NULL;
    if (data) {
        if (page_deserialize(data, len, &p) != 0) qlog("store: corrupt page %s, starting blank", path);
        free(data);
    }
    if (!p) p = page_new(w, h, nb->paper);
    if (!p) return -1;
    scale_page(p, w, h);
    *out = p;
    return 0;
}

int store_save_page(const NotebookInfo *nb, int index, const Page *p) {
    if (index < 0 || index >= nb->npages) return -1;
    return write_page_file(nb, nb->page_ids[index], p);
}

// ---- page format ----

typedef struct {
    uint8_t *d;
    size_t n, cap;
    bool err;
} W;

static void w_bytes(W *w, const void *p, size_t n) {
    if (w->err) return;
    if (w->n + n > w->cap) {
        size_t nc = w->cap ? w->cap * 2 : 4096;
        while (nc < w->n + n) nc *= 2;
        uint8_t *nd = realloc(w->d, nc);
        if (!nd) {
            w->err = true;
            return;
        }
        w->d = nd;
        w->cap = nc;
    }
    memcpy(w->d + w->n, p, n);
    w->n += n;
}
static void w_u8(W *w, uint8_t v) { w_bytes(w, &v, 1); }
static void w_u16(W *w, uint16_t v) {
    uint8_t b[2] = {(uint8_t)v, (uint8_t)(v >> 8)};
    w_bytes(w, b, 2);
}
static void w_u32(W *w, uint32_t v) {
    uint8_t b[4] = {(uint8_t)v, (uint8_t)(v >> 8), (uint8_t)(v >> 16), (uint8_t)(v >> 24)};
    w_bytes(w, b, 4);
}
static void w_f32(W *w, float f) {
    uint32_t u;
    memcpy(&u, &f, 4);
    w_u32(w, u);
}

int page_serialize(const Page *p, uint8_t **out, size_t *len) {
    W w = {0};
    w_bytes(&w, "QPG1", 4);
    w_u16(&w, 1);
    w_u16(&w, (uint16_t)p->paper);
    w_u32(&w, (uint32_t)p->w);
    w_u32(&w, (uint32_t)p->h);
    w_u32(&w, (uint32_t)p->n);
    for (int i = 0; i < p->n; i++) {
        const Stroke *s = p->strokes[i];
        w_u8(&w, (uint8_t)s->tool);
        w_u8(&w, 0);
        w_u8(&w, 0);
        w_u8(&w, 0);
        w_u32(&w, s->seed);
        const float *f = (const float *)&s->params;
        for (int k = 0; k < 13; k++) w_f32(&w, f[k]);
        w_u32(&w, (uint32_t)s->n);
        for (int k = 0; k < s->n; k++) {
            const PenSample *q = &s->pts[k];
            w_f32(&w, q->x);
            w_f32(&w, q->y);
            w_u16(&w, (uint16_t)lrintf(clampf(q->pressure, 0.f, 1.f) * 65535.f));
            w_u16(&w, (uint16_t)(int16_t)lrintf(clampf(q->tilt_x, -90.f, 90.f) * 100.f));
            w_u16(&w, (uint16_t)(int16_t)lrintf(clampf(q->tilt_y, -90.f, 90.f) * 100.f));
            w_u32(&w, q->t_ms);
        }
    }
    if (w.err) {
        free(w.d);
        return -1;
    }
    *out = w.d;
    *len = w.n;
    return 0;
}

typedef struct {
    const uint8_t *d;
    size_t n, pos;
    bool err;
} R;

static const uint8_t *r_take(R *r, size_t n) {
    if (r->err || r->n - r->pos < n) {
        r->err = true;
        return NULL;
    }
    const uint8_t *p = r->d + r->pos;
    r->pos += n;
    return p;
}
static uint8_t r_u8(R *r) {
    const uint8_t *p = r_take(r, 1);
    return p ? p[0] : 0;
}
static uint16_t r_u16(R *r) {
    const uint8_t *p = r_take(r, 2);
    return p ? (uint16_t)(p[0] | p[1] << 8) : 0;
}
static uint32_t r_u32(R *r) {
    const uint8_t *p = r_take(r, 4);
    return p ? (uint32_t)p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24 : 0;
}
static float r_f32(R *r) {
    uint32_t u = r_u32(r);
    float f;
    memcpy(&f, &u, 4);
    return isfinite(f) ? f : 0.f;
}

#define STROKE_HEADER_BYTES (4 + 4 + 13 * 4 + 4)
#define POINT_BYTES (4 + 4 + 2 + 2 + 2 + 4)

int page_deserialize(const uint8_t *buf, size_t len, Page **out) {
    *out = NULL;
    R r = {buf, len, 0, false};
    const uint8_t *m = r_take(&r, 4);
    if (!m || memcmp(m, "QPG1", 4) != 0) return -1;
    uint16_t ver = r_u16(&r);
    uint16_t paper = r_u16(&r);
    uint32_t w = r_u32(&r), h = r_u32(&r), ns = r_u32(&r);
    if (r.err || ver != 1 || w == 0 || h == 0 || w > 20000 || h > 20000) return -1;
    if (ns > (len - r.pos) / STROKE_HEADER_BYTES) return -1;
    Page *p = page_new((int)w, (int)h, paper < PAPER_COUNT ? (PaperKind)paper : PAPER_BLANK);
    if (!p) return -1;
    for (uint32_t i = 0; i < ns && !r.err; i++) {
        uint8_t tool = r_u8(&r);
        r_take(&r, 3);
        uint32_t seed = r_u32(&r);
        ToolParams prm;
        float *f = (float *)&prm;
        for (int k = 0; k < 13; k++) f[k] = r_f32(&r);
        uint32_t np = r_u32(&r);
        if (r.err || tool >= TOOL_COUNT || np > (len - r.pos) / POINT_BYTES) {
            r.err = true;
            break;
        }
        // Clamp params into their UI ranges so a hostile file cannot make huge dabs.
        int npi;
        const ParamInfo *pi = tool_param_table(&npi);
        for (int k = 0; k < npi; k++) {
            float *v = tool_param_ptr(&prm, &pi[k]);
            *v = clampf(*v, pi[k].min, pi[k].max);
        }
        Stroke *s = stroke_new((ToolKind)tool, &prm, seed);
        if (!s) {
            r.err = true;
            break;
        }
        for (uint32_t k = 0; k < np; k++) {
            PenSample q;
            q.x = clampf(r_f32(&r), -10000.f, 30000.f);
            q.y = clampf(r_f32(&r), -10000.f, 30000.f);
            q.pressure = (float)r_u16(&r) / 65535.f;
            q.tilt_x = (float)(int16_t)r_u16(&r) / 100.f;
            q.tilt_y = (float)(int16_t)r_u16(&r) / 100.f;
            q.t_ms = r_u32(&r);
            stroke_append(s, &q, g_dpi);
        }
        page_add(p, s);
    }
    if (r.err) {
        page_free(p);
        return -1;
    }
    *out = p;
    return 0;
}

// ---- thumbnails ----

int store_save_thumb(const char *id, const Canvas *t) {
    char dir[600], path[700];
    if (store_notebook_dir(id, dir, sizeof dir) != 0) return -1;
    snprintf(path, sizeof path, "%s/thumb.pgm", dir);
    char hdr[64];
    int hl = snprintf(hdr, sizeof hdr, "P5\n%d %d\n255\n", t->w, t->h);
    size_t len = (size_t)hl + (size_t)t->w * (size_t)t->h;
    uint8_t *buf = malloc(len);
    if (!buf) return -1;
    memcpy(buf, hdr, (size_t)hl);
    for (int y = 0; y < t->h; y++) memcpy(buf + hl + (size_t)y * t->w, t->px + (size_t)y * t->stride, (size_t)t->w);
    int rc = write_file_atomic(path, buf, len);
    free(buf);
    return rc;
}

int store_load_thumb(const char *id, Canvas *out) {
    char dir[600], path[700];
    memset(out, 0, sizeof *out);
    if (store_notebook_dir(id, dir, sizeof dir) != 0) return -1;
    snprintf(path, sizeof path, "%s/thumb.pgm", dir);
    size_t len;
    uint8_t *d = read_file(path, &len);
    if (!d) return -1;
    int w = 0, h = 0, mx = 0, off = 0;
    if (sscanf((char *)d, "P5 %d %d %d%n", &w, &h, &mx, &off) != 3 || w <= 0 || h <= 0 || w > 4000 || h > 4000 ||
        mx != 255 || (size_t)off + 1 + (size_t)w * h > len) {
        free(d);
        return -1;
    }
    if (canvas_init(out, w, h) != 0) {
        free(d);
        return -1;
    }
    memcpy(out->px, d + off + 1, (size_t)w * h);
    free(d);
    return 0;
}

// ---- settings ----

static const char *k_tool_keys[TOOL_COUNT] = {"pencil", "mech", "ballpoint", "eraser", "highlighter"};

void settings_default(Settings *s) {
    memset(s, 0, sizeof *s);
    for (int t = 0; t < TOOL_COUNT; t++) tool_params_default(t, &s->tools[t]);
    s->current_tool = TOOL_PENCIL;
    s->panel_x = s->panel_y = -1;
    s->side_button = 2;  // highlighter
    s->mirror_pdf = true;
    s->follow_rotation = true;
    s->pinch_zoom = true;
    s->http_port = 8765;
}

static void calib_kv(InputCalib *c, const char *k, const char *v) {
    if (!strcmp(k, "valid")) c->valid = atoi(v) != 0;
    else if (!strcmp(k, "swap")) c->swap_xy = atoi(v) != 0;
    else if (!strcmp(k, "ax")) c->ax = strtof(v, NULL);
    else if (!strcmp(k, "bx")) c->bx = strtof(v, NULL);
    else if (!strcmp(k, "ay")) c->ay = strtof(v, NULL);
    else if (!strcmp(k, "by")) c->by = strtof(v, NULL);
}

static void settings_cb(void *ctx, const char *k, const char *v) {
    Settings *s = ctx;
    const char *dot = strchr(k, '.');
    if (dot) {
        char head[32];
        size_t hl = (size_t)(dot - k);
        if (hl >= sizeof head) return;
        memcpy(head, k, hl);
        head[hl] = 0;
        const char *field = dot + 1;
        if (!strcmp(head, "pen")) return calib_kv(&s->pen_calib, field, v);
        if (!strcmp(head, "touch")) return calib_kv(&s->touch_calib, field, v);
        for (int t = 0; t < TOOL_COUNT; t++) {
            if (strcmp(head, k_tool_keys[t])) continue;
            int n;
            const ParamInfo *pi = tool_param_table(&n);
            for (int i = 0; i < n; i++)
                if (!strcmp(field, pi[i].key)) {
                    float f = strtof(v, NULL);
                    if (f == f) *tool_param_ptr(&s->tools[t], &pi[i]) = clampf(f, pi[i].min, pi[i].max);
                }
        }
        return;
    }
    if (!strcmp(k, "current_tool")) s->current_tool = (ToolKind)clampi(atoi(v), 0, TOOL_COUNT - 1);
    else if (!strcmp(k, "panel_x")) s->panel_x = atoi(v);
    else if (!strcmp(k, "panel_y")) s->panel_y = atoi(v);
    else if (!strcmp(k, "panel_collapsed")) s->panel_collapsed = atoi(v) != 0;
    else if (!strcmp(k, "side_button")) s->side_button = clampi(atoi(v), 0, 2);
    else if (!strcmp(k, "mirror_pdf")) s->mirror_pdf = atoi(v) != 0;
    else if (!strcmp(k, "follow_rotation")) s->follow_rotation = atoi(v) != 0;
    else if (!strcmp(k, "invert")) s->invert = atoi(v) != 0;
    else if (!strcmp(k, "pinch_zoom")) s->pinch_zoom = atoi(v) != 0;
    else if (!strcmp(k, "settings_version")) s->version = atoi(v);
    else if (!strcmp(k, "http_port")) s->http_port = clampi(atoi(v), 1024, 65535);
}

// Defaults that changed between versions. A saved value still equal to the old default was never
// tuned by the owner, so it moves to the new default; anything they changed stays as it is.
static void settings_upgrade(Settings *s) {
    static const struct {
        ToolKind tool;
        size_t off;
        float old_v;
    } changed[] = {
        {TOOL_PENCIL, offsetof(ToolParams, size_min_mm), 0.30f},
        {TOOL_PENCIL, offsetof(ToolParams, size_max_mm), 0.85f},
        {TOOL_PENCIL, offsetof(ToolParams, tilt_size), 2.6f},
        {TOOL_PENCIL, offsetof(ToolParams, smoothing), 0.25f},
        {TOOL_PENCIL, offsetof(ToolParams, smoothing), 0.12f},
        {TOOL_MECH_PENCIL, offsetof(ToolParams, grain), 0.35f},
        {TOOL_MECH_PENCIL, offsetof(ToolParams, smoothing), 0.20f},
    };
    if (s->version >= SETTINGS_VERSION) return;
    for (size_t i = 0; i < sizeof changed / sizeof changed[0]; i++) {
        float *v = (float *)((char *)&s->tools[changed[i].tool] + changed[i].off);
        ToolParams d;
        tool_params_default(changed[i].tool, &d);
        float nv = *(float *)((char *)&d + changed[i].off);
        if (fabsf(*v - changed[i].old_v) < 0.005f && fabsf(*v - nv) >= 0.005f) {
            qlog("settings: %s default updated %.2f -> %.2f", tool_name(changed[i].tool), *v, nv);
            *v = nv;
        }
    }
    s->version = SETTINGS_VERSION;
}

int settings_load(Settings *s) {
    settings_default(s);
    s->version = 0;  // files written before versioning have no settings_version key
    char path[600];
    snprintf(path, sizeof path, "%s/settings.ini", g_root);
    int rc = ini_parse_file(path, settings_cb, s) == 0 ? 0 : 1;
    if (rc == 0) settings_upgrade(s);
    else s->version = SETTINGS_VERSION;
    return rc;
}

int settings_save(const Settings *s) {
    char path[600];
    snprintf(path, sizeof path, "%s/settings.ini", g_root);
    size_t cap = 8192, n = 0;
    char *buf = malloc(cap);
    if (!buf) return -1;
    n += (size_t)snprintf(buf + n, cap - n,
                          "# Quire settings\ncurrent_tool=%d\npanel_x=%d\npanel_y=%d\npanel_collapsed=%d\n"
                          "side_button=%d\nmirror_pdf=%d\nfollow_rotation=%d\ninvert=%d\npinch_zoom=%d\nhttp_port=%d\n"
                          "settings_version=%d\n",
                          (int)s->current_tool, s->panel_x, s->panel_y, s->panel_collapsed, s->side_button,
                          s->mirror_pdf, s->follow_rotation, s->invert, s->pinch_zoom, s->http_port,
                          SETTINGS_VERSION);
    const InputCalib *cs[2] = {&s->pen_calib, &s->touch_calib};
    const char *cn[2] = {"pen", "touch"};
    for (int i = 0; i < 2; i++)
        n += (size_t)snprintf(buf + n, cap - n, "%s.valid=%d\n%s.swap=%d\n%s.ax=%.6f\n%s.bx=%.6f\n%s.ay=%.6f\n%s.by=%.6f\n",
                              cn[i], cs[i]->valid, cn[i], cs[i]->swap_xy, cn[i], cs[i]->ax, cn[i], cs[i]->bx, cn[i],
                              cs[i]->ay, cn[i], cs[i]->by);
    int np;
    const ParamInfo *pi = tool_param_table(&np);
    for (int t = 0; t < TOOL_COUNT; t++)
        for (int i = 0; i < np; i++)
            n += (size_t)snprintf(buf + n, cap - n, "%s.%s=%.4f\n", k_tool_keys[t], pi[i].key,
                                  *tool_param_ptr((ToolParams *)&s->tools[t], &pi[i]));
    int rc = write_file_atomic(path, buf, n);
    free(buf);
    return rc;
}
